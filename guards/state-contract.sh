#!/usr/bin/env bash
# فاحص عقد الحالة — ANNEX-B8-NL/v1 §٥
# يرفض ولا يُصلح: الإصلاح على صاحب الحالة، فلا يعدّل أحد مخرَج غيره (§٤/٣).
#
# الاستعمال:  guards/state-contract.sh [path/to/active-state.md]
# الخروج:     0 = الحالة مطابقة للعقد · 1 = مرفوضة (والأسباب مطبوعة)
set -uo pipefail

STATE="${1:-inner/الحالة/active-state.md}"
FAIL=0
bad()  { printf '  \033[31m✗\033[0m %s\n' "$*"; FAIL=1; }
good() { printf '  \033[32m✓\033[0m %s\n' "$*"; }

[ -f "$STATE" ] || { echo "FAIL: no state file at $STATE"; exit 1; }
echo "فاحص عقد الحالة — ANNEX-B8-NL/v1"
echo "  الملف: $STATE"

# ---- الحقول الإلزامية (١–٦، ٨–١٢)؛ والحقل ٧ يُفحص منفصلًا لأنه الأشد ----
declare -A FIELDS=(
  [task]="المهمة الواحدة الحية"
  [owner_role_ref]="صاحب المهمة"
  [precondition]="precondition"
  [completion_marker]="completion_marker"
  [idempotency_rule]="idempotency_rule"
  [resume_action]="resume_action"
  [phase]="المرحلة"
  [task_status]="حالة المهمة"
  [steps]="خطوات"
  [blockers]="العوائق"
  [last_green_check]="آخر فحص أخضر"
  [delivery_shape]="شكل التسليم"
  [self_review_line]="سطر مراجعة ذاتية"
  [estimated_real_duration]="المدة الحقيقية المقدرة"
)
# ملاحظة م٢ (موضع رفض ٣-٣): كان الفحص `grep -qF <اسم الحقل>` — أي **وجود العنوان** لا
# المضمون، فيمرّ حقلٌ كُتب اسمه وتُركت قيمته فارغة.
# والإصلاح الأول الذي كتبه م١ كان **معيبًا هو الآخر**: عمّم قياس القيمة السطرية على
# حقلَين قِيميّتهما جدول أسفل العنوان (`خطوات` و`العوائق`)، فرفضهما زورًا، وترك `done`
# زائدًا فكسر الصياغة. والتصحيح: **تصنيف الحقول** لا تعميم فحص واحد عليها.
#   · INLINE  — `- **الاسم:** قيمة`   ⟹ القيمة بعد النقطتين غير فارغة
#   · SECTION — عنوان يتلوه جدول        ⟹ العنوان موجود **وله صف بيانات واحد على الأقل**
INLINE=( task owner_role_ref precondition completion_marker idempotency_rule resume_action \
         phase task_status last_green_check delivery_shape self_review_line estimated_real_duration )
declare -A NAME=(
  [task]="المهمة الواحدة الحية"        [owner_role_ref]="صاحب المهمة"
  [precondition]="precondition"        [completion_marker]="completion_marker"
  [idempotency_rule]="idempotency_rule" [resume_action]="resume_action"
  [phase]="المرحلة"                    [task_status]="حالة المهمة"
  [last_green_check]="آخر فحص أخضر"    [delivery_shape]="شكل التسليم"
  [self_review_line]="سطر مراجعة ذاتية" [estimated_real_duration]="المدة الحقيقية المقدرة"
  [steps]="الخطوات"                    [blockers]="العوائق"
)
OK=0; BAD=0
for k in $(printf '%s\n' "${INLINE[@]}" | sort); do
  N="${NAME[$k]}"
  # التثبيت ببداية السطر وصيغة النقطة — فـ`grep -F` غير المثبّت يلتقط أي ذكر للاسم في
  # قيمة حقل آخر (وهو نمط «المطابقة تطابق نصّها» — واردة-٠٠٢). كشفه امتحان ط١/ط٣ لا المراجعة.
  LINE=$(grep -E "^- \*\*$(printf '%s' "$N" | sed 's/[][\.*^$/]/\\&/g'):\*\*" "$STATE" | head -1)
  if [ -z "$LINE" ]; then bad "$k — الحقل «$N» غير موجود أصلًا (§٦/٢)"; BAD=$((BAD+1)); continue; fi
  VAL=$(printf '%s' "$LINE" | sed "s/.*\*\*${N}:\*\*//")
  TRIM=$(printf '%s' "$VAL" | tr -d '[:space:]')
  if [ -z "$TRIM" ]; then
    bad "$k («$N») موجود **بلا قيمة** — وجود عنوان لا مضمون (§٦/٢)"; BAD=$((BAD+1))
  else
    good "$k («$N») — قيمة ${#TRIM} حرفًا"; OK=$((OK+1))
  fi
done
# SECTION: عنوان يتلوه جدول — يشترط صف بيانات واحدًا على الأقل (لا عنوانًا فارغًا)
for k in steps blockers; do
  N="${NAME[$k]}"
  grep -qF "$N" "$STATE" || { bad "$k — القسم «$N» غير موجود (§٦/٢)"; BAD=$((BAD+1)); continue; }
  # صفوف البيانات: أسطر تبدأ بـ | وليست سطر الفصل |---|
  ROWS=$(awk -v n="$N" 'index($0,n){f=1} f&&/^\|/{c++} f&&/^$/{if(c)exit} END{print c+0}' "$STATE")
  SEP=$(awk -v n="$N" 'index($0,n){f=1} f&&/^\|[ :-]*\|$/{c++} f&&/^$/{if(c)exit} END{print c+0}' "$STATE")
  DATA=$((ROWS-SEP-1)); [ "$DATA" -lt 0 ] && DATA=0
  if [ "$DATA" -eq 0 ]; then
    bad "$k — القسم «$N» عنوان أو ترويسة **بلا صف بيانات** (§٦/٢، م٣)"; BAD=$((BAD+1))
  else
    good "$k — القسم «$N» فيه $DATA صف بيانات"; OK=$((OK+1))
  fi
done
DENO=$((OK+BAD))
[ "$BAD" -eq 0 ] && good "كل الحقول مستوفاة بقيمة: $OK/$DENO (المقام مشتقّ لا مكتوب)" \
                 || bad "$BAD حقلًا من $DENO ناقص المضمون"

# ---- ٧: الخطوة التالية حرفيًا — موجودة وغير فارغة ----
# العلة المصححة: كان الفحص يقرأ السطر التالى بعد العلامة، فيمتلئ دائمًا بال bullet الذي يليه
# ويمرّر خطوة فارغة. الصحيح: افصل ما بعد العلامة على السطر نفسه، ثم جرّده من التنصيص والترقيم
# والمسافات، ولا تقبل إلا نصًّا فعليًّا. والسبب أن §٦/٢ يشترط «فعلًا واحدًا قابلًا للتنفيذ
# فور الاستيقاظ بلا تفكير» — فالعلامة بلا فعل تعني أن الوكيل سيستيقظ ولا يعرف ما يفعل.
if grep -qE "^- \*\*الخطوة التالية حرفيًا:\*\*" "$STATE"; then
  INLINE=$(grep -E "^- \*\*الخطوة التالية حرفيًا:\*\*" "$STATE" | head -1 \
           | sed 's/.*الخطوة التالية حرفيًا//' \
           | tr -d '*:：•\t ' )
  # لا استثناء احتياطيًّا يقرأ السطر التالي: كان يملأ الفراغ من أي bullet تالٍ
  # (مثل «سطر مراجعة ذاتية») فيمرّر خطوة فارغة. العلامة وحدها بلا فعل = حالة مرفوضة،
  # لأن §٦/٢ يشترط فعلًا واحدًا قابلًا للتنفيذ فور الاستيقاظ بلا تفكير.
  if [ -n "$INLINE" ]; then
    good "next_step_literal: ${#INLINE} حرفًا من الفعل"
  else
    bad "«الخطوة التالية حرفيًا» علامة بلا فعل (§٦/٢) — الوكيل سيستيقظ ولا يعرف ما يفعل"
  fi
else
  bad "حقل next_step_literal ناقص (§٦/٢) — يُشترط سطر نقطيّ مثبّت «- **الخطوة التالية حرفيًا:** فعل»"
fi

# ---- §٢/١١: الحالة بملك م١ دائمًا ----
# §٢/١١ — يفحص **اسم الحقل المعرَّف في العقد** (owner_role_ref = «صاحب المهمة») لا نصًّا
# مخترعًا. ملاحظة م٢ (موضع رفض ٣): كان يفحص «مالك الحالة الحالي:» وهو مفتاح لا وجود له
# في العقد، فيمرّ فراغًا عند إسناد «صاحب المهمة» إلى م٢ — وهو عين نمط واردة-٠٠٢ §١.
OWN=$(sed -n 's/^- \*\*صاحب المهمة:\*\* *//p' "$STATE" | head -1)
[ -n "$OWN" ] || bad "§٢/١١ — حقل «صاحب المهمة» غائب أو فارغ (فحص وجود لا مضمون)"
case "$OWN" in
  *م٢*|*المحقق*) bad "§٢/١١ — نُسبت ملكية الحالة/المهمة إلى المحقق («$OWN»). يُمنع «مالك الحالة الحالي: المحقق»؛ الصحيح: «بانتظار حكم المحقق، والحالة بملك مدير التشغيل»" ;;
  *م١*) : ;;
  *) bad "§٢/١١ — «صاحب المهمة» = «$OWN» لا يحوي م١ (مدير التشغيل يملك الحالة دائمًا)" ;;
esac
if grep -qE "مالك الحالة الحالي: *(المحقق|م٢)" "$STATE"; then
  bad "«مالك الحالة الحالي: المحقق» — ممنوع بنص §٢/١١. الصحيح: «بانتظار حكم المحقق، والحالة بملك مدير التشغيل»"
else
  good "§٢/١١ — لم تُنسب ملكية الحالة إلى المحقق"
fi

# ---- م١٠/٦: لا كلمة «شغال» بلا تسمية بيئة وزاوية تحقق ----
# العلة المصححة: كان البحث عن زاوية التحقق يجري على الملف كله، فأي كلمة «قياس» في أي موضع
# آخر تُبرّئ ادعاء «شغال» غير مقيس. والصحيح أن الزاوية يجب أن تكون في السطر نفسه الذي يحمل
# الادعاء — فم١٠/٦ يحظر كلمة «شغال» بلا تسمية البيئة وزاوية التحقق معًا.
SHIKH=$(grep -nE "شغال|شغّال" "$STATE" || true)
if [ -n "$SHIKH" ]; then
  OFF=0
  while IFS= read -r line; do
    [ -z "$line" ] && continue
    TXT=$(printf '%s' "$line" | cut -d: -f2-)
    if printf '%s' "$TXT" | grep -qE "زاوية|بيئة"; then
      good "«شغال» مقترنة بتسمية زاوية/بيئة في السطر نفسه (م١٠/٦)"
    else
      bad "سطر $(printf '%s' "$line" | cut -d: -f1): «شغال» بلا تسمية بيئة وزاوية — محظور بنص م١٠/٦"
      OFF=1
    fi
  done <<< "$SHIKH"
else
  good "لا ادعاء «شغال» غير مقيس"
fi

# ---- §٤/٦: حارة واحدة حية ----
# العلة المصححة (فحص فراغي — vacuous probe): كان يعدّ العلامة `**الحارة**` و`lane:`،
# وكلاهما **لا وجود له** في عقد ANNEX-B8-NL/v1؛ فالحقل اسمه «المهمة الواحدة الحية».
# فكان العداد صفرًا دائمًا و`0 > 1` كاذبة ⟹ الفحص يمرّ بلا أن يقيس شيئًا قطّ.
# وهذا ما يحرّمه تفسير م٢ v1.1 §٣: «الممنوع نجاح probe على مقام غير معلن أو fixture فارغ».
# الإصلاح: (أ) عدّ الحقل الفعلي. (ب) المطلوب **واحد بالضبط** لا ≤١، فالصفر رفض أيضًا —
# حالة بلا مهمة حية لا تُقلع منها جولة (واو م١١: خطوة تالية واحدة حرفية).
# (ج) يُطبع المقام المعلن والسبب في الدليل (v1.1 §٣/٣).
LANE_MARKER="المهمة الواحدة الحية"
LANE_EXPECTED=1                       # مقام معلن مسبقًا (v1.1 §٣/١)
LANES=$(awk -v m="$LANE_MARKER" 'index($0,m) && /^- *\*\*/ {n++} END{print n+0}' "$STATE")
LANE_TOTAL=$(grep -cE '^- *\*\*' "$STATE" || true)   # مقام المطبوع: كل الحقول النقطية
if [ "${LANES:-0}" -eq "$LANE_EXPECTED" ]; then
  good "حارة واحدة حية (§٤/٦) — مقاس=$LANES، المقام المعلن=$LANE_EXPECTED، من $LANE_TOTAL حقلًا نقطيًّا"
else
  bad "$LANES حارة حيّة مقابل مقام معلن $LANE_EXPECTED (من $LANE_TOTAL حقلًا نقطيًّا) — §٤/٦: التوازي الوحيد المشروع خيوط البحث (م٨)"
fi

# ---- م١١/٢: كل عائق مصنف ----
# العلة المصححة: كان الفحص يقرأ أول جدول عوائق فقط، فأي جدول لاحق غير مصنف يمرّ.
# والصحيح فحص كل صف بيانات في كل جدول عوائق: بوابة التنفيذ م١١/٢ هي
# `blocking_open = 0` و `unclassified = 0` — فلا يكفي أن يكون بعض العوائق مصنفًا.
ROWS_TOTAL=0; ROWS_CLS=0
while IFS= read -r row; do
  case "$row" in
    *"---"*) continue ;;                       # سطر فاصل
    *"العائق"*"|"*"التاريخ"*|*"التصنيف"*) continue ;;  # ترويسة
  esac
  ROWS_TOTAL=$((ROWS_TOTAL+1))
  if printf '%s' "$row" | grep -qE 'blocking-owner|blocking-research|reversible-default|irrelevant-to-scope'; then
    ROWS_CLS=$((ROWS_CLS+1))
  fi
done < <(sed -n '/## *العوائق/,$p' "$STATE" | grep '^|' || true)

if [ "$ROWS_TOTAL" -eq 0 ]; then
  good "لا عوائق معلنة"
elif [ "$ROWS_CLS" -eq "$ROWS_TOTAL" ]; then
  good "كل العوائق مصنفة (م١١/٢): $ROWS_CLS/$ROWS_TOTAL"
else
  bad "$((ROWS_TOTAL-ROWS_CLS)) عائقًا بلا تصنيف من $ROWS_TOTAL (م١١/٢) — بوابة التنفيذ unclassified = 0"
fi

echo
if [ "$FAIL" -eq 0 ]; then echo "OK — الحالة مطابقة لعقد ANNEX-B8-NL/v1"; else echo "REJECTED — أصلح ما أعلاه ثم اعد الفحص"; fi
exit "$FAIL"
